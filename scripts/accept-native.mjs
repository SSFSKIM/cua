// --- 10. packaging ---------------------------------------------------------------------------------------------------
async function item10() {
  const checks = [];
  const readme = readFileSync(join(REPO, 'README.md'), 'utf8');
  const needed = ['npm test', 'npm run build:helper', 'npm run test:helper', 'cua.mjs install', 'doctor', 'secrets set', 'serve', 'claude mcp add', 'accept-native.mjs', 'Developer ID', 'Chrome'];
  const absent = needed.filter(text => !readme.includes(text));
  checks.push(check('README: standalone requirements, limitations and exact commands', absent.length ? 'FAIL' : 'PASS', absent.length ? `missing: ${absent.join(', ')}` : `mentions ${needed.join(', ')}`));
  const plugin = parseJson(readFileSync(join(REPO, '.claude-plugin', 'plugin.json'), 'utf8'));
  const server = plugin?.mcpServers?.cua_repl;
  // hooks/hooks.json carries the Elicitation auto-accept and the /secret mod's module; never Stop/SubagentStop.
  const hooksFile = join(REPO, 'hooks', 'hooks.json');
  const shellHooks = Object.keys((existsSync(hooksFile) && parseJson(readFileSync(hooksFile, 'utf8'))?.hooks) || {});
  const pluginOk = server?.command === 'node' && server.args?.some(a => a.endsWith('/cua-shim.mjs')) && !plugin.hooks && !shellHooks.some(e => e === 'Stop' || e === 'SubagentStop');
  checks.push(check('plugin launches the standalone server; no Stop/SubagentStop hooks', pluginOk ? 'PASS' : 'FAIL', `cua_repl: ${server ? `${server.command} ${server.args.join(' ')}` : 'missing'}; shell hooks ${plugin?.hooks ? 'in the manifest' : shellHooks.join(', ') || 'none'}`));

  const tracked = sh('git', ['-C', REPO, 'ls-files']).split('\n').filter(Boolean);
  const badTracked = forbiddenPaths(tracked);
  const userHome = homedir();
  const code = tracked.filter(p => !p.startsWith('docs/') && !/\.md$/.test(p) && existsSync(join(REPO, p)));
  const personal = code.filter(p => { const text = readFileSync(join(REPO, p), 'latin1'); return text.includes(userHome + '/') || tokenLike(text); });
  checks.push(check('nothing tracked is an archive, runtime, credential, log or machine-specific token', tracked.length && !badTracked.length && !personal.length ? 'PASS' : 'FAIL',
    `${tracked.length} tracked files; forbidden: ${badTracked.join(', ') || 'none'}; code/config naming this user's home or holding token-like strings: ${personal.join(', ') || 'none'}`));

  const pack = await run('npm', ['pack', '--dry-run', '--json'], {env: suiteEnv()});
  const packed = parseJson(pack.stdout);
  const entry = Array.isArray(packed) ? packed[0] : packed && Object.values(packed)[0];
  const files = entry?.files?.map(f => f.path) ?? [];
  const missing = missingFromPackage(files);
  const badPacked = forbiddenPaths(files);
  const untracked = files.filter(f => !tracked.includes(f));
  checks.push(check('package files: what runs, diagnoses and builds the helper; nothing else', files.length && !missing.length && !badPacked.length && !untracked.length ? 'PASS' : 'FAIL',
    `${files.length} files${missing.length ? `; missing ${missing.join(', ')}` : ''}${badPacked.length ? `; forbidden ${badPacked.join(', ')}` : ''}${untracked.length ? `; untracked ${untracked.join(', ')}` : ''}`));

  const spawnsClaude = code.filter(p => /\.(mjs|js|json|sh)$/.test(p)).filter(p => /spawn\w*\(\s*['"]claude['"]|exec\w*\(\s*['"]claude['"]|['"]claude['"],\s*\[['"]mcp['"]/.test(readFileSync(join(REPO, p), 'utf8')));
  checks.push(check('existing MCP registration untouched', spawnsClaude.length ? 'FAIL' : 'PASS',
    spawnsClaude.length ? `code that runs claude: ${spawnsClaude.join(', ')}` : 'no tracked code runs `claude` or edits ~/.claude; registration is documented (README) and never executed by acceptance'));

  const head = sh('git', ['-C', REPO, 'rev-parse', '--short', 'HEAD']).trim();
  const branch = sh('git', ['-C', REPO, 'rev-parse', '--abbrev-ref', 'HEAD']).trim();
  const dirty = sh('git', ['-C', REPO, 'status', '--porcelain']).trim().length > 0;
  const clone = mkdtempSync('/tmp/cua-clean.');
  try {
    const cloned = await run('git', ['clone', '--quiet', '--branch', branch, REPO, join(clone, 'cua')], {cwd: clone, timeoutMs: 120_000});
    if (cloned.code !== 0) checks.push(check('clean clone builds and tests', 'FAIL', `git clone failed: ${cloned.stderr.trim()}`));
    else {
      const dir = join(clone, 'cua');
      const [node] = await suites(dir, {label: 'clean clone: '});
      // build:helper installs what it built into $CUA_HOME/bin: here a home inside the clone directory, never the user's.
      const build = await run('npm', ['run', 'build:helper'], {cwd: dir, env: {...suiteEnv(), CUA_HOME: join(clone, 'home')}});
      const buildCheck = check('clean clone: npm run build:helper', build.code === 0 ? 'PASS' : 'FAIL', `exit ${build.code ?? build.error} in ${seconds(build.ms)}`);
      const helper = build.code === 0 ? await helperSuite(dir, {label: 'clean clone: '}) : check('clean clone: npm run test:helper', 'FAIL', 'not run: build:helper failed');
      checks.push(node, buildCheck, helper);
      // This runner holds the pattern itself, so it is not searched.
      const researchRefs = sh('git', ['-C', dir, 'grep', '-l', '-e', 'codex-app-src', '--', ':!docs', ':!*.md', ':!scripts/accept-native.mjs']).trim();
      checks.push(check('clean clone needs no research trees', researchRefs ? 'FAIL' : 'PASS', researchRefs ? `code referring to research trees: ${researchRefs}` : 'no code or config outside docs refers to the local research trees'));
    }
  } finally { rmSync(clone, {recursive: true, force: true}); }
  addItem(10, 'Packaging, plugin README, tracked files, clean checkout', checks, {head, branch, workingTreeDirty: dirty, cloneRemoved: !existsSync(clone)});
}

