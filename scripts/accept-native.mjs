#!/usr/bin/env node
// Acceptance runner for the native + secrets slice (spec acceptance 1-10). It runs every automated check against the
// installed runtime in an explicit scratch $CUA_HOME, inventories the release gates this machine cannot prove, and
// writes a per-item PASS/FAIL/BLOCKED report. Only a check that ran and passed is PASS; anything skipped, opt-in and
// not requested, or waiting on a human or another environment is BLOCKED with what it needs.
//
//   export CUA_HOME="$(mktemp -d /tmp/cua-accept.XXXXXX)"
//   node bin/cua.mjs install --archive <pinned ChatGPT zip>
//   node scripts/accept-native.mjs [--live-secrets] [--live-textedit] [--archive <zip>] --report "$CUA_HOME/acceptance.json"
//   node scripts/accept-native.mjs --live-secrets --live-textedit --secret-key <KEY> [--secret-home <dir>] --report …
//
// --secret-key types a key the caller stored beforehand (`HOME=<dir> node bin/cua.mjs secrets set <KEY>`) instead of a
// generated one; its store is the one under --secret-home, by default $HOME, which must not be this account's home.
// Pass --secret-home rather than exporting HOME for the whole run: the runner's other native checks (verify.mjs,
// probe-lifecycle) find the computer-use socket under $HOME. The caller's key and home are left in place.
//
// What runs:
//   1  `npm test` in this checkout
//   2  the installed release, its verification, a reinstall that must change nothing (it never downloads: without
//      --archive it passes a path that does not exist, which only a non-verified install would ever read)
//   3  `cua doctor --json` on the installed home and on an empty one
//   4  `node verify.mjs`, plus the native no-account check (the runtime's own CODEX_HOME holds no auth file)
//   5  --live-textedit only: scripts/accept/textedit.mjs (one disposable TextEdit document)
//   6  in a temporary $HOME store only (never ~/.config/claude-secrets): `secrets set` without a terminal, then at a
//      pty (masked, typed twice), `secrets list --json`, `secrets remove`; MCP `secrets_list`; --live-secrets runs
//      scripts/probe-secrets.mjs (generated sentinels in its own temporary $HOME, removed in finally); with both flags
//      the TextEdit fixture also types {{secret:KEY}} into its document and reads it back (target observation): a
//      generated value under a generated key in a temporary $HOME it removes, or the caller's --secret-key
//   7  substitution suites, and the live probe's substitution steps when --live-secrets ran it, with its trusted-root
//      rows: unwritable under the scoped default (a guarantee) and, informational (INFO), what an explicit disabled allows
//   8  lifecycle suites, scripts/probe-lifecycle.mjs (live, read-only), per-connection approvals (--live-textedit)
//   9  release gates: clean machine, cold start, fresh permission onboarding (always BLOCKED here)
//   10 README/plugin/package contents, tracked files, and a clean clone of HEAD running npm test (deleted afterwards)
// The report holds metadata only. Values generated by the live fixtures never leave them; the report is checked for
// them before it is written. Nothing here registers an MCP server or edits ~/.claude. Exit 0 PASS, 1 FAIL, 3 BLOCKED.
