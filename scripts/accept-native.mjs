// Every CLI step runs against a temporary $HOME's store, never the account's ~/.config/claude-secrets.
async function item6(probe, textedit) {
  const checks = [];
  const storeHome = createStoreHome('cua-accept-secrets-');
  const cli = (args, timeoutMs = 30_000) => run(process.execPath, [CLI, 'secrets', ...args], {env: cuaEnv({HOME: storeHome}), timeoutMs});
  const store = fileStore({dir: storeDir({HOME: storeHome})});
  const listed = async () => { try { return await store.list(); } catch { return null; } };
  const key = generatedKey('CUA_ACCEPT_SET');
  const value = `CUASET${randomBytes(12).toString('hex').toUpperCase()}`;
  forbidden.push(value);
  try {
    const noTty = generatedKey('CUA_ACCEPT_NOTTY');
    const set = await cli(['set', noTty]);
    checks.push(check('secrets set requires a terminal', set.code !== 0 && /terminal/i.test(set.stderr) && !(await listed() ?? []).includes(noTty) ? 'PASS' : 'FAIL',
      `without a terminal: exit ${set.code}, "${sanitize(set.stderr.trim().split('\n').at(-1) ?? '')}"; ${(await listed() ?? []).includes(noTty) ? 'a file was created' : 'nothing was stored'}`));

    const seeded = await seedSecret({home: storeHome, key, value});
    let roundTrip = false, modes = '';
    try {
      roundTrip = await store.read(key) === value;
      modes = `directory ${(statSync(store.dir).mode & 0o777).toString(8)}, file ${(statSync(join(store.dir, key)).mode & 0o777).toString(8)}`;
    } catch (error) { modes = `read refused: ${error.code}`; }
    checks.push(check('secrets set at a terminal: masked, typed twice, stored exactly, 0600 in 0700',
      seeded.exit === 0 && seeded.prompts === 2 && !seeded.echoed && roundTrip && modes === 'directory 700, file 600' ? 'PASS' : 'FAIL',
      `on a pty: exit ${seeded.exit ?? seeded.signal}${seeded.timedOut ? ' (timed out)' : ''}, ${seeded.prompts} prompt(s) answered, value ${seeded.echoed ? 'ECHOED' : 'never echoed'}; the file reads back ${roundTrip ? 'exactly the typed value' : 'something else'}; ${modes}`));

    const list = await cli(['list', '--json']);
    const json = parseJson(list.stdout);
    const labelsOnly = list.code === 0 && json && Object.keys(json).sort().join() === 'labels,ok' && json.labels.every(isLabel) && json.labels.includes(key) && !list.stdout.includes(value);
    checks.push(check('secrets list returns keys only', labelsOnly ? 'PASS' : 'FAIL',
      labelsOnly ? `{ok, labels}: the stored key and no value (${json.labels.length} key(s))` : `exit ${list.code}; ${json ? `keys ${Object.keys(json).join(',')}` : 'no JSON'}`));

    const removed = await cli(['remove', key, '--yes']);
    const gone = !(await listed() ?? [key]).includes(key);
    checks.push(check('secrets remove deletes the key\'s file', removed.code === 0 && gone ? 'PASS' : 'FAIL', `exit ${removed.code}; the key is ${gone ? 'gone' : 'still listed'}`));
  } finally {
    const cleaned = await removeStoreHome({home: storeHome, key});
    checks.push(check('the temporary store home is removed', cleaned.keyGone && cleaned.homeGone ? 'PASS' : 'FAIL', cleaned.homeGone ? 'removed' : 'still present'));
  }
  const mcp = state.verify?.secretsList;
  checks.push(check('MCP secrets_list returns keys only', mcp?.status === 'ok' && Number.isInteger(mcp.labelCount) ? 'PASS' : mcp ? 'BLOCKED' : 'FAIL',
    mcp ? `verify.mjs: ${JSON.stringify(mcp)}` : 'verify.mjs produced no secrets_list result'));
  checks.push(fromSuite('masked prompt: no-terminal refusal, nothing echoed, mismatch, empty and cancel store nothing', ['test/secrets-cli.test.mjs']));
  if (!probe) checks.push(NOT_REQUESTED('--live-secrets'));
  else checks.push(...probeChecks(probe, probePhasesFor(6)));
  if (textedit?.scenario === 'live-textedit-with-secret') {
    // The optional UI delivery counts only if it actually happened: each of its steps must have run and passed.
    for (const step of SECRET_STEPS) checks.push(inventoryCheck(`UI delivery (optional, combined): ${step.slice('secret: '.length)}`, textedit.steps, [step]));
  }
  const evidence = {
    ...(probe && !probe.missing ? {liveSecrets: {status: probe.status, key: probe.label, steps: probe.steps, runtimeFiles: probe.runtimeFiles,
      channels: probe.channels?.map(c => ({name: c.name, bytes: c.bytes, containsReference: c.containsReference}))}} : {}),
    ...(textedit?.scenario === 'live-textedit-with-secret' ? {uiDelivery: {key: textedit.observations.secretLabel, callerKey: Boolean(callerSecret)}} : {}),
  };
  addItem(6, 'Secrets: terminal-only masked set, key-only listing, live store roundtrip', checks, Object.keys(evidence).length ? evidence : undefined);
}

