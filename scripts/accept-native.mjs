const sh = (command, args, opts = {}) => { try { return execFileSync(command, args, {encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...opts}); } catch (error) { return error.stdout ?? ''; } };

// A child with captured output and a hard time limit. It leads its own process group, so a timeout stops it and what
// it started in that group (npm's test runner, say) and nothing else.
function run(command, args, {cwd = REPO, env = process.env, timeoutMs = 600_000, stdin = 'ignore'} = {}) {
  return new Promise(resolve => {
    const started = Date.now();
    const child = spawn(command, args, {cwd, env, stdio: [stdin, 'pipe', 'pipe'], detached: true});
    let stdout = '', stderr = '';
    child.stdout.on('data', d => { stdout += d; });
    child.stderr.on('data', d => { stderr += d; });
    const timer = setTimeout(() => { try { process.kill(-child.pid, 'SIGKILL'); } catch {} }, timeoutMs);
    child.on('error', error => { clearTimeout(timer); resolve({code: null, error: error.code ?? error.message, stdout, stderr, ms: Date.now() - started}); });
    child.on('exit', (code, signal) => { clearTimeout(timer); resolve({code, signal, timedOut: signal === 'SIGKILL', stdout, stderr, ms: Date.now() - started}); });
  });
}
// Suites run without this run's scratch home or any server setting in their environment.
const suiteEnv = () => Object.fromEntries(Object.entries(process.env).filter(([key]) => key !== 'CUA_HOME' && !key.startsWith('CUA_SHIM_')));
const cuaEnv = extra => ({...process.env, CUA_HOME: home, ...extra});
const parseJson = text => { try { return JSON.parse(text); } catch { return null; } };
const seconds = ms => `${(ms / 1000).toFixed(1)} s`;
const ended = r => r.timedOut ? `timed out after ${seconds(r.ms)}` : `exit ${r.code ?? r.error ?? r.signal}`;
const noisy = text => /\b(ExperimentalWarning|DeprecationWarning|Warning:)/.test(text);

function addItem(id, title, checks, evidence) {
  const item = {id, title, status: rollup(checks.map(c => c.status)), checks};
  if (evidence) item.evidence = evidence;
  items.push(item);
  console.error(`accept-native: ${id}. ${title}: ${item.status}`);
  return item;
}

// --- 1. suites -------------------------------------------------------------------------------------------------
async function suites(cwd, {label}) {
  const out = [];
  const node = await run('npm', ['test'], {cwd, env: testReporterEnv(suiteEnv()), timeoutMs: 300_000});
  const summary = testSummary(node.stdout);
  const {totals} = summary;
  const failed = [...node.stdout.matchAll(/^not ok \d+ - (.*)$/gm)].map(m => m[1]);
  const verdict = suiteVerdict({code: node.code, ...summary});
  out.push(check(`${label}npm test`, verdict.status,
    totals ? `${verdict.reason}; ${totals.fail} failed${failed.length ? ` (${failed.join('; ')})` : ''}, ${totals.skipped} skipped, ${totals.todo} TODO in ${seconds(node.ms)}${noisy(node.stdout + node.stderr) ? '; output has warnings' : ''}` : `${ended(node)}; ${verdict.reason}${failed.length ? ` (failed before that: ${failed.join('; ')})` : ''}`,
    {totals}));
  return out;
}
async function helperSuite(cwd, {label}) {
  const r = await run('npm', ['run', 'test:helper'], {cwd, env: testReporterEnv(suiteEnv())});
  // swift-testing's summary ("Test run with N tests in M suites passed|failed ..."); XCTest's own line reports 0.
  const swift = (r.stdout + r.stderr).match(/Test run with (\d+) tests? in \d+ suites? (passed|failed)/);
  const summary = testSummary(r.stdout);
  const node = summary.totals;
  const nodeVerdict = suiteVerdict({code: r.code, ...summary});
  const swiftSkipped = /^\S*\s*Test .* skipped/m.test(r.stdout + r.stderr);
  const swiftStatus = r.code !== 0 || !swift || swift[2] !== 'passed' ? 'FAIL' : Number(swift[1]) === 0 || swiftSkipped ? 'BLOCKED' : 'PASS';
  return check(`${label}npm run test:helper`, rollup([swiftStatus, nodeVerdict.status]),
    `${ended(r)} in ${seconds(r.ms)}; Swift ${swift ? `${swift[1]} tests ${swift[2]}${swiftSkipped ? ', some skipped' : ''}` : 'summary not found'}; Node-driven executable tests: ${nodeVerdict.reason}`,
    {swiftTests: swift ? Number(swift[1]) : null, nodeTests: node?.tests ?? null});
}

const state = {};

async function item1() {
  const checks = await suites(REPO, {label: ''});
  state.npmTest = checks[0].status;
  const helper = locateHelper({path: BUILD_OUTPUT});
  if (!helper.built) checks.push(check('npm run test:helper', 'BLOCKED', 'the Keychain helper is not built in this checkout: run npm run build:helper first (the clean clone in item 10 builds it from scratch)'));
  else checks.push(await helperSuite(REPO, {label: ''}));
  state.helperSuite = checks.at(-1).status;
  checks.push(check('npm run build:helper (this checkout)', helper.built ? 'PASS' : 'BLOCKED', helper.built
    ? 'the production helper is built here and was exercised by test:helper; item 10 rebuilds it in a clean clone'
    : 'not built; run npm run build:helper'));
  addItem(1, 'Node-only npm test; actual Swift helper build and test:helper', checks);
}

// --- 2. install ----------------------------------------------------------------------------------------------------
// A claim backed by a suite carries that suite's own verdict from item 1: it passes only if the suite executed every
// test and all passed.
const fromSuite = (name, files) => check(name, state.npmTest ?? 'FAIL',
  state.npmTest === 'PASS' ? `covered by npm test (${files.join(', ')}), which executed and passed every test in item 1` : `npm test was ${state.npmTest ?? 'not run'} in item 1; see ${files.join(', ')}`);
const fromHelperSuite = (name, detail) => check(name, state.helperSuite ?? 'FAIL',
  state.helperSuite === 'PASS' ? `npm run test:helper (item 1): ${detail}` : `npm run test:helper was ${state.helperSuite ?? 'not run'} in item 1`);

async function item2() {
  const checks = [];
  const pin = selectPin(loadPins());
  let runtime;
  try {
    runtime = resolveRuntime({home});
    const record = readInstalledRecord(runtime.root, runtime.manifest);
    checks.push(check('installed release', runtime.release === pin.release ? 'PASS' : 'FAIL',
      `active ${runtime.release} (pin ${pin.release}), installed from ${record.source}, archive sha256 ${record.archive.sha256.slice(0, 12)}…, ${record.archive.length} bytes`));
  } catch (error) {
    checks.push(check('installed release', 'FAIL', `${error.code}: ${sanitize(error.message)}`));
  }
  const doctorChecks = state.doctor?.checks ?? [];
  const verified = ['runtime.files', 'runtime.vendor-manifest', 'runtime.ipc', 'runtime.signatures'].map(name => doctorChecks.find(c => c.name === name));
  checks.push(check('verified private runtime tree', verified.every(c => c?.status === 'pass') ? 'PASS' : 'FAIL',
    verified.map(c => c ? `${c.name} ${c.status}` : 'missing').join('; ') + ` (${sanitize(doctorChecks.find(c => c.name === 'runtime.signatures')?.detail ?? '')})`));
  if (runtime && verified.every(c => c?.status === 'pass')) {
    const before = snapshotTree(runtime.root);
    const reinstall = await run(process.execPath, [CLI, 'install', '--json', '--archive', options.archive ?? NO_DOWNLOAD_GUARD], {env: cuaEnv()});
    const result = parseJson(reinstall.stdout);
    const diff = diffSnapshots(before, snapshotTree(runtime.root));
    checks.push(check('reinstall mutates nothing', reinstall.code === 0 && result?.changed === false && diff.same ? 'PASS' : 'FAIL',
      `install --json → ${result ? `ok ${result.ok}, changed ${result.changed}` : `exit ${reinstall.code}: ${sanitize(reinstall.stderr.trim().split('\n').at(-1) ?? '')}`}; ${before.size} entries compared (type, mode, size, mtime, inode): ${diff.same ? 'identical' : `${diff.added.length} added, ${diff.removed.length} removed, ${diff.changed.length} changed`}`));
  } else checks.push(check('reinstall mutates nothing', 'FAIL', 'not attempted: the installed release does not verify'));
  checks.push(fromSuite('bad hash, length, manifest or signature never activates', ['test/runtime-install.test.mjs', 'test/runtime-manifest.test.mjs', 'test/cli.test.mjs']));
  const changed = sh('git', ['-C', REPO, 'log', '--format=%h', `${DOWNLOAD_EVIDENCE.commit}..HEAD`, '--', ...DOWNLOAD_EVIDENCE.paths]).trim();
  const known = sh('git', ['-C', REPO, 'cat-file', '-t', DOWNLOAD_EVIDENCE.commit]).trim() === 'commit';
  checks.push(check('download mode (official pinned URL)', !known ? 'BLOCKED' : changed ? 'BLOCKED' : 'PASS', !known
    ? 'cannot tell whether the acquisition code changed since the recorded download proof; rerun: CUA_HOME="$(mktemp -d /tmp/cua-download.XXXXXX)" node bin/cua.mjs install'
    : changed ? `acquisition code changed since ${DOWNLOAD_EVIDENCE.commit} (${changed.split('\n').join(', ')}): rerun CUA_HOME="$(mktemp -d /tmp/cua-download.XXXXXX)" node bin/cua.mjs install`
      : `cited, not rerun: ${DOWNLOAD_EVIDENCE.doc} (byte-identical tree from the official URL); acquisition code unchanged since ${DOWNLOAD_EVIDENCE.commit}`,
    {evidence: changed || !known ? 'needs rerun' : 'cited'}));
  addItem(2, 'Pinned install: verified private tree, idempotent reinstall, refusal of bad archives, download mode', checks);
}

